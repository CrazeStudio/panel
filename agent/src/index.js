app.use((error, _req, res, _next) => {
  console.error(error);
  const status = Number.isInteger(error.status) ? error.status : 400;
  res.status(status).json({ error: error.message || 'Agent request failed.' });
});

const server = app.listen(PORT, HOST, async () => {
  console.log(`CrazePanel node agent listening on http://${HOST}:${PORT}`);
  try {
    await docker.ping();
    await reconnectExistingConsoles();
    console.log('Docker engine connected.');
  } catch (error) {
    console.error('Docker engine is not available:', error.message);
  }
});

function shutdown(signal) {
  console.log(`Received ${signal}; stopping agent.`);
  server.close(() => process.exit(0));
  setTimeout(() => process.exit(1), 10000).unref();
}

process.on('SIGINT', () => shutdown('SIGINT'));
process.on('SIGTERM', () => shutdown('SIGTERM'));
