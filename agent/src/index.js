app.post('/api/servers/:id/files', async (req, res, next) => {
  try {
    const root = serverDirectory(req.params.id);
    const action = req.body?.action;
    const relative = String(req.body?.path || '');

    if (action === 'mkdir') {
      await createDirectory(root, relative);
      return res.status(201).json({ ok: true });
    }

    if (action === 'create') {
      if (typeof req.body?.content !== 'string') return res.status(400).json({ error: 'File content must be text.' });
      const result = await writeFile(root, relative, req.body.content, { exclusive: true, maximumBytes: MAX_TEXT_BYTES });
      return res.status(201).json(result);
    }

    if (action === 'upload') {
      const name = String(req.body?.name || '');
      const content = req.body?.contentBase64;
      const maxBase64Bytes = Math.ceil(MAX_UPLOAD_BYTES / 3) * 4;
      const validBase64 = typeof content === 'string' && /^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(content);
      if (!name || name.includes('/') || name.includes('\\') || name.startsWith('.') ||
          !validBase64 || content.length > maxBase64Bytes) {
        return res.status(400).json({ error: 'Invalid upload.' });
      }

      const data = Buffer.from(content, 'base64');
      if (data.length > MAX_UPLOAD_BYTES) return res.status(413).json({ error: 'File exceeds the 64 MB upload limit.' });
      const destination = [relative, name].filter(Boolean).join('/');
      const result = await writeFile(root, destination, data, { exclusive: true, maximumBytes: MAX_UPLOAD_BYTES });
      return res.status(201).json(result);
    }

    if (action === 'rename') {
      const sourcePath = String(req.body?.sourcePath || '');
      const name = String(req.body?.name || '');
      if (!sourcePath || !/^[a-zA-Z0-9_ .()-]{1,120}$/.test(name) || name.startsWith('.')) {
        return res.status(400).json({ error: 'Provide a valid source path and new file name.' });
      }

      return res.json(await renameFile(root, sourcePath, name));
    }

    return res.status(400).json({ error: 'Unsupported file operation.' });
  } catch (error) {
    next(error);
  }
});

