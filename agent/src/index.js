app.post('/api/servers', async (req, res, next) => {
  try {
    const { serverId, name, eggId, version, memoryMb, cpuCores, port } = req.body || {};
    if (!safeServerId(serverId)) return res.status(400).json({ error: 'Invalid server identifier.' });

    const egg = eggs[eggId];
    if (!egg) return res.status(400).json({ error: 'Unsupported server egg.' });

    const memory = Number(memoryMb);
    const cpu = Number(cpuCores);
    const hostPort = Number(port);
    if (!Number.isInteger(memory) || memory < 1024 || memory > 131072 ||
        !Number.isFinite(cpu) || cpu < 0.5 || cpu > 64 ||
        !Number.isInteger(hostPort) || hostPort < 1 || hostPort > 65535) {
      return res.status(400).json({ error: 'Invalid server resource limits or port.' });
    }

    const directory = serverDirectory(serverId);
    fs.mkdirSync(directory, { recursive: true, mode: 0o700 });
    const env = [
      'EULA=TRUE',
      `TYPE=${egg.type || 'PAPER'}`,
      `VERSION=${version || 'LATEST'}`,
      `MEMORY=${memory}M`,
      `SERVER_NAME=${String(name || 'Minecraft Server').slice(0, 64)}`,
      'ENABLE_RCON=true',
      `RCON_PASSWORD=${crypto.randomBytes(18).toString('hex')}`,
    ];

    const result = await createServer({
      serverId,
      name,
      eggId,
      image: egg.image,
      containerPort: egg.containerPort,
      port: hostPort,
      memoryMb: memory,
      cpuCores: cpu,
      env,
      directory,
    });

    res.status(201).json(result);
  } catch (error) {
    next(error);
  }
});

app.get('/api/servers/:id', async (req, res, next) => {
  try {
    const state = await inspectServer(req.params.id);
    if (!state.exists) return res.status(404).json({ error: 'Managed container not found.' });

    let stats = null;
    if (state.status === 'running') {
      try { stats = await getStats(req.params.id); } catch { stats = null; }
    }
    res.json({ ...state, stats });
  } catch (error) {
    next(error);
  }
});

