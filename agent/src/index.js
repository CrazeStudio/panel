app.get('/api/servers/:id/backups', async (req, res, next) => {
  try {
    const serverId = req.params.id;
    if (!safeServerId(serverId)) return res.status(400).json({ error: 'Invalid server identifier.' });
    const directory = path.join(BACKUP_ROOT, serverId);
    await fs.promises.mkdir(directory, { recursive: true });
    const names = (await fs.promises.readdir(directory))
      .filter((name) => /^[a-zA-Z0-9_.-]+\.tar\.gz$/.test(name));

    const backups = await Promise.all(names.map(async (name) => {
      const stat = await fs.promises.stat(path.join(directory, name));
      return { name, size: stat.size, createdAt: stat.mtime.toISOString() };
    }));
    res.json({ backups: backups.sort((a, b) => b.createdAt.localeCompare(a.createdAt)) });
  } catch (error) {
    next(error);
  }
});

app.post('/api/servers/:id/backups', async (req, res, next) => {
  try {
    const serverId = req.params.id;
    const source = serverDirectory(serverId);
    const directory = path.join(BACKUP_ROOT, serverId);
    await fs.promises.mkdir(directory, { recursive: true });
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
    const name = `${timestamp}.tar.gz`;
    const archive = path.join(directory, name);
    await runTar(['--numeric-owner', '-czf', archive, '-C', source, '.']);
    const stat = await fs.promises.stat(archive);
    res.status(201).json({ name, size: stat.size, createdAt: stat.mtime.toISOString() });
  } catch (error) {
    next(error);
  }
});

app.post('/api/servers/:id/backups/restore', async (req, res, next) => {
  try {
    const serverId = req.params.id;
    if (!safeServerId(serverId)) return res.status(400).json({ error: 'Invalid server identifier.' });
    const name = String(req.body?.name || '');
    if (!/^[a-zA-Z0-9_.-]+\.tar\.gz$/.test(name)) return res.status(400).json({ error: 'Invalid backup name.' });

    const state = await inspectServer(serverId);
    if (state.status === 'running') return res.status(409).json({ error: 'Stop the server before restoring a backup.' });

    const archive = path.join(BACKUP_ROOT, serverId, name);
    await fs.promises.access(archive);
    const source = serverDirectory(serverId);
    const staging = source + '.restore-' + crypto.randomBytes(5).toString('hex');
    await fs.promises.mkdir(staging, { recursive: true });

    try {
      const listing = await runTar(['-tzf', archive]);
      const entries = listing.split(/\r?\n/).filter(Boolean);
      if (entries.some((entry) => {
        const normalized = path.posix.normalize(entry.replace(/^\.\//, ''));
        return path.posix.isAbsolute(normalized) || normalized === '..' || normalized.startsWith('../');
      })) {
        throw new Error('Backup contains an unsafe path.');
      }
      await runTar(['--no-same-owner', '--no-same-permissions', '-xzf', archive, '-C', staging]);
      await fs.promises.rm(source, { recursive: true, force: true });
      await fs.promises.rename(staging, source);
    } catch (error) {
      await fs.promises.rm(staging, { recursive: true, force: true });
      throw error;
    }

    res.json({ ok: true, restored: name });
  } catch (error) {
    next(error);
  }
});

app.get('/api/servers/:id/backups/:name/download', async (req, res, next) => {
  try {
    const serverId = req.params.id;
    const name = String(req.params.name || '');
    if (!safeServerId(serverId) || !/^[a-zA-Z0-9_.-]+\.tar\.gz$/.test(name)) {
      return res.status(400).json({ error: 'Invalid backup identifier.' });
    }
    const archive = path.join(BACKUP_ROOT, serverId, name);
    const resolved = path.resolve(archive);
    const root = path.resolve(BACKUP_ROOT, serverId) + path.sep;
    if (!resolved.startsWith(root)) return res.status(400).json({ error: 'Invalid backup path.' });
    const stat = await fs.promises.stat(resolved);
    if (!stat.isFile()) return res.status(404).json({ error: 'Backup not found.' });
    if (stat.size > 64 * 1024 * 1024) return res.status(413).json({ error: 'Backup exceeds the 64 MB download limit.' });
    const content = await fs.promises.readFile(resolved);
    res.json({ name, size: content.length, contentBase64: content.toString('base64') });
  } catch (error) {
    if (error.code === 'ENOENT') return res.status(404).json({ error: 'Backup not found.' });
    next(error);
  }
});

