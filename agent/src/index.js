function authenticate(req, res, next) {
  const supplied = String(req.get('authorization') || '').replace(/^Bearer\\s+/i, '');
  const expected = Buffer.from(TOKEN);
  const actual = Buffer.from(supplied);

  if (actual.length !== expected.length || !crypto.timingSafeEqual(actual, expected)) {
    return res.status(401).json({ error: 'Invalid node authentication token.' });
  }
  next();
}

function serverDirectory(serverId) {
  if (!safeServerId(serverId)) throw new Error('Invalid server identifier.');
  return path.join(DATA_ROOT, serverId);
}

function runTar(args) {
  return new Promise((resolve, reject) => {
    const child = spawn('tar', args, { stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (chunk) => { stdout += chunk.toString(); });
    child.stderr.on('data', (chunk) => { stderr += chunk.toString(); });
    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) resolve(stdout);
      else reject(new Error(stderr.trim() || `tar exited with code ${code}`));
    });
  });
}

async function listFiles(serverId, relative) {
  const root = serverDirectory(serverId);
  const directory = resolveInside(root, relative || '');
  const entries = await fs.promises.readdir(directory, { withFileTypes: true });

  const files = await Promise.all(entries.filter((item) => !item.name.startsWith('.')).map(async (item) => {
    const full = path.join(directory, item.name);
    const stat = await fs.promises.lstat(full);
    if (stat.isSymbolicLink()) return null;

    return {
      name: item.name,
      type: item.isDirectory() ? 'directory' : 'file',
      size: stat.size,
      modifiedAt: stat.mtime.toISOString(),
    };
  }));

  return {
    path: relative || '',
    files: files.filter(Boolean).sort((a, b) => {
      if (a.type !== b.type) return a.type === 'directory' ? -1 : 1;
      return a.name.localeCompare(b.name);
    }),
  };
}

